// ODsay는 "수도권 2호선", "인천 1호선"처럼 지역을 붙이고
// 급행이면 "9호선(급행)"처럼 괄호를 답니다. 색은 같으므로 모두 떼어냅니다.
export function shortLine(name: string): string {
  const s = (name || "")
    .replace(/^수도권\s*/, "")
    .replace(/^인천\s*(\d)/, "인천$1")
    .replace(/\s*\([^)]*\)\s*$/, "")
    .trim();
  return ALIASES[s] ?? s;
}

export function lineColor(name: string): string {
  return LINE_COLORS[shortLine(name)] ?? "#6B7280";
}
